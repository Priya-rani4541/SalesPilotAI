"""Call summary endpoints.

- POST /api/summaries/generate : summarise a call, a conversation or a raw transcript
- GET  /api/summaries          : list stored summaries (optional filters + paging)
- GET  /api/summaries/{id}     : view one summary

A summary is generated by Gemini from the transcript and persisted in the
"call_summaries" collection, linked to the call, conversation and lead. Failures
are mapped to clean HTTP errors (400 / 429 / 502 / 503).
"""

from typing import Any, Optional

from fastapi import APIRouter, HTTPException, Query

from app.schemas.summary import (
    CallSummary,
    Sentiment,
    SummaryGenerateRequest,
    SummaryListResponse,
)
from app.services.summary_service import (
    SummaryConfigurationError,
    SummaryInputError,
    SummaryRateLimitError,
    SummaryService,
    SummaryUpstreamError,
)
from app.services.summary_store import SummaryStore, SummaryStoreError

router = APIRouter()

_service = SummaryService(SummaryStore())


def _to_summary(document: dict[str, Any]) -> CallSummary:
    """Map a MongoDB summary document to the API model (_id -> id)."""
    data = dict(document)
    data["id"] = data.pop("_id", data.get("id"))
    return CallSummary(**data)


def _map_error(exc: Exception) -> HTTPException:
    """Translate a summary error into a clean HTTP response."""
    if isinstance(exc, SummaryInputError):
        return HTTPException(status_code=400, detail=str(exc))
    if isinstance(exc, (SummaryConfigurationError, SummaryStoreError)):
        return HTTPException(status_code=503, detail=str(exc))
    if isinstance(exc, SummaryRateLimitError):
        return HTTPException(status_code=429, detail=str(exc), headers={"Retry-After": "60"})
    if isinstance(exc, SummaryUpstreamError):
        return HTTPException(status_code=502, detail=str(exc))
    raise exc


@router.post(
    "/generate",
    response_model=CallSummary,
    status_code=201,
    summary="Generate a call summary",
)
def generate_summary(payload: SummaryGenerateRequest) -> CallSummary:
    """Generate (or regenerate) a summary from a call, conversation or transcript."""
    try:
        document = _service.generate(payload)
    except Exception as exc:  # noqa: BLE001 - mapped to a clean HTTP error below
        raise _map_error(exc) from exc
    return _to_summary(document)


@router.get("", response_model=SummaryListResponse, summary="List call summaries")
def list_summaries(
    call_id: Optional[str] = Query(default=None, description="Filter by call id."),
    conversation_id: Optional[str] = Query(default=None, description="Filter by conversation id."),
    lead_id: Optional[str] = Query(default=None, description="Filter by lead id."),
    sentiment: Optional[Sentiment] = Query(default=None, description="Filter by sentiment."),
    limit: int = Query(default=50, ge=1, le=200, description="Page size."),
    skip: int = Query(default=0, ge=0, description="Number of summaries to skip."),
) -> SummaryListResponse:
    """Return stored summaries matching the filters, newest first."""
    try:
        total, documents = _service.list_summaries(
            call_id=call_id,
            conversation_id=conversation_id,
            lead_id=lead_id,
            sentiment=sentiment.value if sentiment else None,
            limit=limit,
            skip=skip,
        )
    except SummaryStoreError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc

    summaries = [_to_summary(document) for document in documents]
    return SummaryListResponse(total=total, count=len(summaries), summaries=summaries)


@router.get("/{summary_id}", response_model=CallSummary, summary="View one summary")
def get_summary(summary_id: str) -> CallSummary:
    """Return a single summary by id."""
    try:
        document = _service.get(summary_id)
    except SummaryStoreError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc

    if document is None:
        raise HTTPException(status_code=404, detail=f"Summary '{summary_id}' was not found.")
    return _to_summary(document)
